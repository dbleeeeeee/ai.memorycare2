export function guessTopic(text){
  let best=null,bestN=0;
  for(const [t,ws] of Object.entries(KEYWORDS)){
    const n=ws.reduce((a,w)=>a+(text.includes(w)?(w.length>=3?2:1):0),0);
    if(n>bestN){best=t;bestN=n}
  }
  return best;
}

// 관람자 문장에 가장 잘 이어지는 어르신 기억 고르기
export function findMatch(text, seed=Date.now()){
  const topic=guessTopic(text);
  const yr=(text.match(/(19[3-9]\d|20[0-2]\d)/)||[])[0];
  let cand=ELDERS;
  if(topic) cand=cand.filter(e=>e.topic===topic);
  if(yr){ const y=+yr; const near=cand.filter(e=>Math.abs(e.year-y)<=8); if(near.length) cand=near; }
  const words=text.replace(/[^\p{L}\p{N}\s]/gu,' ').split(/\s+/).filter(w=>w.length>=2);
  const scored=cand.map(e=>({e,s:words.reduce((a,w)=>a+(e.sentence.includes(w)?1:0),0)}));
  const max=Math.max(...scored.map(x=>x.s));
  const top=scored.filter(x=>x.s===max).map(x=>x.e);
  const pick=top[seed%top.length];
  return {topic, match:pick};
}
